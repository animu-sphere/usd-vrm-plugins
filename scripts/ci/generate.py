"""Render OST source CI as a callable workflow; --check rejects drift.

OST 0.23.13 cannot render workflow_call. This repository-owned adapter only
changes the trigger and event guards; every build/test/package step and matrix
comes verbatim from the pinned OST. Unexpected generator shapes fail closed.
Remove the adapter when OST has an equivalent native reusable-workflow contract.
"""
from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from ci_pins import declared_bootstrap_version

OUTPUT = ROOT / ".github/workflows/ost-source-ci.yml"
HEADER = (
    "# Generated by scripts/ci/generate.py from openstrata.ci.yaml and pinned OST.\n"
    "# Regenerate with: python scripts/ci/generate.py (never edit this file).\n"
)


def adapt(raw: str) -> str:
    trigger = "on:\n  pull_request:\n"
    guard = "    if: github.event_name == 'pull_request'\n"
    jobs = re.findall(r"^  ([a-zA-Z0-9_-]+):\n", raw.split("\njobs:\n", 1)[1], re.M)
    if not jobs or any(not job.startswith("pr") for job in jobs):
        raise ValueError("adapter only supports the PR source lane")
    if raw.count(trigger) != 1 or raw.count(guard) != len(jobs):
        raise ValueError("OST trigger/guard format changed; review the adapter")
    if not raw.startswith("# Generated by `ost ci generate github`"):
        raise ValueError("unexpected OST workflow header")
    raw = HEADER + "\n".join(raw.split("\n")[2:])
    raw = raw.replace(trigger, "on:\n  workflow_call:\n  workflow_dispatch:\n")
    return raw.replace(guard, "    if: github.event_name == 'pull_request' || github.event_name == 'workflow_dispatch'\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ost", default="ost")
    args = parser.parse_args()
    version = subprocess.check_output([args.ost, "--version"], text=True).strip()
    expected = f"ost {declared_bootstrap_version()}"
    if version != expected:
        raise ValueError(f"generation requires {expected}, got {version}")
    raw = subprocess.check_output(
        [args.ost, "ci", "generate", "github", "--stdout"],
        cwd=ROOT, text=True, encoding="utf-8")
    rendered = adapt(raw)
    if args.check:
        actual = OUTPUT.read_text(encoding="utf-8")
        if actual != rendered:
            sys.stderr.writelines(difflib.unified_diff(
                actual.splitlines(keepends=True), rendered.splitlines(keepends=True),
                fromfile=str(OUTPUT), tofile="regenerated"))
            return 1
        print("Generated source CI matches its inputs.")
    else:
        OUTPUT.write_text(rendered, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
